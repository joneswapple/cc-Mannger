export type Lang = "zh" | "en";
const LANG_KEY = "ccm_lang";

function initialLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "zh" || v === "en") return v;
  } catch {
    // fall through
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function lookup(dict: unknown, key: string): string | undefined {
  let cur: unknown = dict;
  for (const part of key.split(".")) {
    if (cur && typeof cur === "object" && part in cur) cur = (cur as Record<string, unknown>)[part];
    else return undefined;
  }
  return typeof cur === "string" ? cur : undefined;
}

export type T = (key: string, vars?: Record<string, string | number>) => string;

function makeT(lang: Lang): T {
  return (key, vars) => {
    const raw = (lang === "en" ? lookup(en, key) : undefined) ?? lookup(zh, key) ?? key;
    return vars ? raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : raw;
  };
}

const Ctx = createContext<{ lang: Lang; t: T; toggle: () => void }>({
  lang: "zh",
  t: makeT("zh"),
  toggle: () => {},
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);
  const toggle = () => {
    const next = lang === "zh" ? "en" : "zh";
    setLang(next);
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      // session only
    }
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
  };
  return <Ctx.Provider value={{ lang, t: makeT(lang), toggle }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
